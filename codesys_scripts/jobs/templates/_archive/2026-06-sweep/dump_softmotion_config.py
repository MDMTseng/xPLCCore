# -*- coding: ascii -*-
# Dump SoftMotion configuration (axis group, kinematics, axes) to a YAML
# snapshot under doc/softmotion_snapshot.yaml. Run periodically and commit
# the snapshot so kinematic / axis-group changes show up in git diffs.
#
# Why: SoftMotion config (SpiderR kinematic chain, axis modulo settings,
# scaling factors) lives entirely inside the binary CODESYS project file.
# Without a snapshot, changes are invisible to code review and rollback.
# This dump is best-effort - it captures what the scripting API exposes,
# not the full project state.

