def to_yaml(obj, indent=0):
    pad = "  " * indent
    out = []
    if isinstance(obj, dict):
        if not obj:
            return "{}"
        for k, v in obj.items():
            ks = str(k)
            if isinstance(v, (dict, list)) and v:
                out.append("{}{}:".format(pad, ks))
                out.append(to_yaml(v, indent + 1))
            else:
                vs = to_yaml(v, indent + 1)
                if isinstance(v, str) and ("\n" in v or len(v) > 80):
                    out.append("{}{}: |".format(pad, ks))
                    for line in v.splitlines():
                        out.append("  " * (indent + 1) + line)
                else:
                    out.append("{}{}: {}".format(pad, ks, vs))
    elif isinstance(obj, list):
        if not obj:
            return "[]"
        for item in obj:
            if isinstance(item, (dict, list)):
                out.append("{}-".format(pad))
                out.append(to_yaml(item, indent + 1))
            else:
                out.append("{}- {}".format(pad, to_yaml(item, indent + 1)))
    elif isinstance(obj, bool):
        return "true" if obj else "false"
    elif obj is None:
        return "null"
    elif isinstance(obj, (int, float)):
        return str(obj)
    else:
        s = str(obj)
        # Escape if contains special yaml chars
        if any(c in s for c in ":#[]{},&*!|>%@`'\""):
            s = '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
        return s
    return "\n".join(out)


yaml_text = to_yaml(snapshot)

with open(OUT_PATH, "w") as f:
    f.write(yaml_text)
    f.write("\n")

