OUT_PATH = os.path.join(REPO_ROOT, "doc", "softmotion_snapshot.yaml")


def safe_name(o):
    try: return o.get_name()
    except Exception: return "?"


def safe_type(o):
    try: return str(o.type)
    except Exception:
        try: return type(o).__name__
        except Exception: return "?"


def deep(o, d=0, max_d=10):
    if d > max_d: return
    yield o, d
    try:
        for c in o.get_children():
            for x, dd in deep(c, d + 1, max_d): yield x, dd
    except Exception:
        pass


def get_text(o, attr):
    try:
        v = getattr(o, attr, None)
        return getattr(v, "text", None) if v is not None else None
    except Exception:
        return None


def dump_obj_attrs(o):
    """Best-effort attribute dump — most SoftMotion config objects don't
    expose readable attributes via the public scripting API, so this
    is mostly empty. We capture what we can."""
    out = {}
    try:
        for k in dir(o):
            if k.startswith("_"): continue
            try:
                v = getattr(o, k)
                if callable(v): continue
                s = repr(v)
                if len(s) > 300: s = s[:300] + "..."
                # Filter out boilerplate
                if k in ("get_name", "get_children", "type"): continue
                out[k] = s
            except Exception:
                pass
    except Exception:
        pass
    return out


